-- ID corto y visible por tarea, para poder referenciarlas (ej. en dependencias).
alter table public.tasks add column display_id integer generated by default as identity;
alter table public.tasks add constraint tasks_display_id_key unique (display_id);

-- Vinculo informativo entre tareas (NO bloquea nada, solo deja asentada la dependencia).
create table public.task_dependencies (
  task_id uuid not null references public.tasks(id) on delete cascade,
  depends_on_task_id uuid not null references public.tasks(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (task_id, depends_on_task_id),
  check (task_id <> depends_on_task_id)
);

create index task_dependencies_task_id_idx on public.task_dependencies (task_id);
create index task_dependencies_depends_on_idx on public.task_dependencies (depends_on_task_id);

alter table public.task_dependencies enable row level security;

create policy "task_dependencies_select" on public.task_dependencies
  for select using (public.is_master() or public.is_project_member(public.project_of_task(task_id)));

create policy "task_dependencies_write" on public.task_dependencies
  for all using (public.is_master() or public.is_project_team(public.project_of_task(task_id)))
  with check (public.is_master() or public.is_project_team(public.project_of_task(task_id)));
